#!/usr/bin/env bash
set -euo pipefail

ROOT="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd -P)"
BUILD_DIR="$ROOT/build-ci-ucrt64-gcc"
CPM_DIR="$ROOT/.cache/cpm"
CACHE_MARKER="$CPM_DIR/.eden-ucrt64-gcc-cache"

section() {
    printf '\n============================================================\n'
    printf '%s\n' "$1"
    printf '============================================================\n'
}

die() {
    printf '\nERROR: %s\n' "$*" >&2
    exit 1
}

normalize_windows_path() {
    cygpath -am "$1" | tr '\\' '/'
}

[[ "${MSYSTEM:-}" == "UCRT64" ]] ||
    die "This must run inside the MSYS2 UCRT64 environment."

for tool in git gcc g++ cmake ninja objdump cygpath; do
    command -v "$tool" >/dev/null 2>&1 ||
        die "Required UCRT64 tool '$tool' was not found. Run Setup-Eden-CI-MSYS2.ps1 first."
done

cd "$ROOT"

section "Eden CI-style UCRT64 GCC build"
printf 'Source:      %s\n' "$ROOT"
printf 'Build:       %s\n' "$BUILD_DIR"
printf 'Environment: %s\n' "$MSYSTEM"
printf 'Compiler:    %s\n' "$(gcc --version | head -n 1)"
printf 'CMake:       %s\n' "$(cmake --version | head -n 1)"
printf 'Ninja:       %s\n' "$(ninja --version)"

if git rev-parse --is-inside-work-tree >/dev/null 2>&1; then
    printf 'Branch:      %s\n' "$(git branch --show-current)"
    printf 'Commit:      %s\n' "$(git rev-parse HEAD)"
    if ! git diff --quiet || ! git diff --cached --quiet; then
        printf 'Notice:      the source worktree has local modifications.\n'
    fi
fi

# The source tree hardcodes .cache/cpm as CPM_SOURCE_CACHE. Preserve any cache
# produced by the prior MSVC build, then allow UCRT64/GCC to create its own.
if [[ -d "$CPM_DIR" && ! -f "$CACHE_MARKER" ]]; then
    stamp="$(date +%Y%m%d-%H%M%S)"
    backup="$ROOT/.cache/cpm-before-ucrt64-gcc-$stamp"
    section "Quarantining the existing compiler-specific CPM cache"
    printf 'Moving:\n  %s\nTo:\n  %s\n' "$CPM_DIR" "$backup"
    mv "$CPM_DIR" "$backup"
fi

mkdir -p "$CPM_DIR"
: > "$CACHE_MARKER"

# Never reuse a build tree generated by Visual Studio, MSVC, Clang, or another
# source path. CMake records Windows-style paths while MSYS2 uses POSIX-style
# paths, so normalize both sides before comparing them.
if [[ -f "$BUILD_DIR/CMakeCache.txt" ]]; then
    generator="$(sed -n 's/^CMAKE_GENERATOR:INTERNAL=//p' "$BUILD_DIR/CMakeCache.txt" | tr -d '\r')"
    compiler="$(sed -n -E 's/^CMAKE_CXX_COMPILER:(FILEPATH|STRING)=//p' "$BUILD_DIR/CMakeCache.txt" | tr -d '\r')"
    home="$(sed -n 's/^CMAKE_HOME_DIRECTORY:INTERNAL=//p' "$BUILD_DIR/CMakeCache.txt" | tr -d '\r')"

    root_cmp="$(normalize_windows_path "$ROOT")"
    home_cmp="$(normalize_windows_path "$home")"
    root_cmp="${root_cmp,,}"
    home_cmp="${home_cmp,,}"

    compiler_ok=false
    if [[ "$compiler" == "g++" || "$compiler" == "c++" ]]; then
        compiler_ok=true
    elif [[ -n "$compiler" ]]; then
        compiler_cmp="$(normalize_windows_path "$compiler")"
        gxx_cmp="$(normalize_windows_path "$(command -v g++)")"
        cxx_cmp="$(normalize_windows_path "$(dirname "$(command -v g++)")/c++.exe")"
        compiler_cmp="${compiler_cmp,,}"
        gxx_cmp="${gxx_cmp,,}"
        cxx_cmp="${cxx_cmp,,}"

        if [[ "$compiler_cmp" == "$gxx_cmp" || "$compiler_cmp" == "$cxx_cmp" ]]; then
            compiler_ok=true
        fi
    fi

    if [[ "$generator" != "Ninja" ||
          "$home_cmp" != "$root_cmp" ||
          "$compiler_ok" != true ]]; then
        section "Removing an incompatible CI build directory"
        printf 'Cached generator: %s\n' "$generator"
        printf 'Cached source:    %s\n' "$home"
        printf 'Cached compiler:  %s\n' "$compiler"
        rm -rf "$BUILD_DIR"
    fi
fi

section "Configuring exactly along the GCC-standard CI route"

cmake -S "$ROOT" -B "$BUILD_DIR" -G Ninja \
    -DBUILD_TESTING=OFF \
    -DYUZU_TESTS=OFF \
    -DCMAKE_BUILD_TYPE=Release \
    -DYUZU_USE_BUNDLED_QT=ON \
    -DYUZU_USE_QT_MULTIMEDIA=OFF \
    -DYUZU_USE_QT_WEB_ENGINE=OFF \
    -DENABLE_QT_TRANSLATION=ON \
    -DENABLE_UPDATE_CHECKER=OFF \
    -DUSE_CCACHE=ON \
    -DCCACHE_PATH=sccache \
    -DUSE_DISCORD_PRESENCE=ON \
    -DENABLE_LTO=OFF \
    -DYUZU_USE_BUNDLED_SIRIT=ON \
    -DYUZU_USE_BUNDLED_FFMPEG=ON \
    -DYUZU_USE_BUNDLED_MOLTENVK=ON \
    -DYUZU_DISABLE_LLVM=ON \
    -DYUZU_STATIC_BUILD=ON \
    -DCMAKE_INSTALL_PREFIX=/usr \
    -DYUZU_CMD=ON \
    -DYUZU_ROOM_STANDALONE=OFF \
    -DBUILD_ID=amd64 \
    -DNIGHTLY_BUILD=ON \
    -DYUZU_USE_BUNDLED_SDL3=ON \
    -DYUZU_USE_BUNDLED_SDL2=ON \
    -DYUZU_USE_BUNDLED_OPENSSL=ON \
    -DCMAKE_C_FLAGS="-march=x86-64-v3 -mtune=generic -O3" \
    -DCMAKE_CXX_FLAGS="-march=x86-64-v3 -mtune=generic -O3"

section "Building with Ninja"
cmake --build "$BUILD_DIR"

EDEN_EXE="$BUILD_DIR/bin/eden.exe"
[[ -f "$EDEN_EXE" ]] || die "The build ended without producing $EDEN_EXE"

section "Checking runtime dependencies"
imports="$(objdump -p "$EDEN_EXE" | awk '/DLL Name:/ {print $3}' | sort -fu)"
printf '%s\n' "$imports"

if printf '%s\n' "$imports" |
    grep -Eiq '^(libgcc|libstdc\+\+|libwinpthread|Qt6|SDL|avcodec|avformat|avutil|libssl|libcrypto)'; then
    printf '\nWARNING: Non-system runtime DLL imports were detected.\n' >&2
    printf 'The executable built, but it is not as self-contained as the official static build.\n' >&2
fi

section "BUILD SUCCEEDED"
printf 'Executable:\n  %s\n' "$EDEN_EXE"
